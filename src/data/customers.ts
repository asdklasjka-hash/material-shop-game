export function pickShiftCustomers(count = 5, lastAnimalIds: AnimalId[] = []): CustomerRequest[] {
  const allAnimals: AnimalId[] = [
    'rabbit',
    'bear',
    'fox',
    'panda',
    'puppy',
    'cat',
    'monkey',
    'penguin',
  ];

  // Shuffle animals cleanly
  const shuffledAnimals = [...allAnimals].sort(() => Math.random() - 0.5);
  // Prioritize animals not seen at the very end of previous day if possible
  const ordered = [
    ...shuffledAnimals.filter((a) => !lastAnimalIds.includes(a)),
    ...shuffledAnimals.filter((a) => lastAnimalIds.includes(a)),
  ].slice(0, count);

  return ordered.map((animalId) => {
    const pool = CUSTOMER_REQUESTS.filter((r) => r.animalId === animalId);
    const chosen = pool[Math.floor(Math.random() * pool.length)];
    return chosen;
  });
}
